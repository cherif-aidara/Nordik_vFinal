class Command(BaseCommand):
    help = "Importe les données de stock de démonstration pour Nordik Adventures."

    def handle(self, *args, **options):
        self.stdout.write("Import des catégories, fournisseurs et produits de démo...")

        created_products = 0

        for (
            sku,
            cat_name,
            name,
            cost,
            price,
            margin,
            qty,
            reorder,
            safety,
            supplier_name,
            supplier_code,
            supplier_discount,
            delay,
            weight,
            entry_date,
            location,
        ) in PRODUCT_ROWS:
            category, _ = ProductCategory.objects.get_or_create(name=cat_name)
            supplier, _ = Supplier.objects.get_or_create(
                code=supplier_code,
                defaults={
                    "name": supplier_name,
                    "default_discount": supplier_discount,
                    "delivery_delay_days": delay,
                },
            )

            product, created = Product.objects.get_or_create(
                sku=sku,
                defaults={
                    "category": category,
                    "name": name,
                    "purchase_cost": cost,
                    "sale_price": price,
                    "gross_margin_percent": margin,
                    "quantity_in_stock": qty,
                    "reorder_threshold": reorder,
                    "safety_stock": safety,
                    "supplier": supplier,
                    "supplier_discount": supplier_discount,
                    "weight_kg": weight,
                    "stock_entry_date": entry_date,
                    "warehouse_location": location,
                    "status": Product.STATUS_ACTIVE,
                },
            )

            if created:
                created_products += 1

        self.stdout.write(
            self.style.SUCCESS(
                f"Import terminé : {created_products} produit(s) créés/ajoutés."
            )
        )


